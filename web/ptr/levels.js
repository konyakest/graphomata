  function ladder(n) {
    const edges = [];
    for (let i = 0; i + 1 < n; i++) edges.push([i, i + 1], [n + i, n + i + 1], [i, n + i]);
    edges.push([n - 1, 2 * n - 1]);
    return { nodes: 2 * n, edges };
  }
